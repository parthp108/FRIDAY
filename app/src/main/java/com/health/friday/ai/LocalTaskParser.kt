 * ============================================================================
 * LOCAL TASK PARSER
 * ============================================================================
 *
 * TODO:
 * - Something actionable that needs to be done today.
 *
 * Goal:
 * - A longer-term outcome, normally spanning several days or more.
 *
 * Examples:
 *
 * "buy groceries"
 *      -> TODO
 *
 * "finish my assignment"
 *      -> TODO
 *
 * "finish my assignment this week"
 *      -> GOAL
 *
 * "get fit this month"
 *      -> GOAL
 *
 * Time-specific small actions belong to LocalReminderParser instead.
 */

