package com.health.friday.memory.rag

import kotlin.math.sqrt

object VectorMath {
    fun cosineSimilarity(v1: FloatArray, v2: FloatArray): Float {
        if (v1.size != v2.size || v1.isEmpty()) return 0f
        var dotProduct = 0f
        var norm1 = 0f
        var norm2 = 0f
        for (i in v1.indices) {
            dotProduct += v1[i] * v2[i]
            norm1 += v1[i] * v1[i]
            norm2 += v2[i] * v2[i]
        }
        return if (norm1 == 0f || norm2 == 0f) 0f else (dotProduct / (sqrt(norm1) * sqrt(norm2)))
    }
}